import { createClient, SupabaseClient } from "@supabase/supabase-js";

export interface WhitelistRecord {
  id?: number;
  user_id: number;
  target_login: string;
  target_id?: number | null;
  created_at?: string;
}

export const SUPABASE_WHITELIST_TABLE_SQL = `
-- Supabase Schema for GitHub Social Manager Whitelist
create table if not exists github_whitelist (
  id bigint generated by default as identity primary key,
  user_id bigint not null,
  target_login text not null,
  target_id bigint,
  created_at timestamp with time zone default timezone('utc'::text, now()) not null,
  constraint unique_user_target unique(user_id, target_login)
);

-- Index for fast user lookups
create index if not exists idx_github_whitelist_user on github_whitelist(user_id);

-- Optional Row Level Security (RLS) policy
alter table github_whitelist enable row level security;
create policy "Allow all access with service role or anon key" 
  on github_whitelist 
  for all 
  using (true) 
  with check (true);
`.trim();

/**
 * Checks whether Supabase connection credentials are configured in the environment
 */
export function isSupabaseConfigured(): boolean {
  const url = process.env.SUPABASE_URL || process.env.NEXT_PUBLIC_SUPABASE_URL;
  const key =
    process.env.SUPABASE_SERVICE_ROLE_KEY ||
    process.env.SUPABASE_ANON_KEY ||
    process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;
  return Boolean(url && key);
}

let cachedClient: SupabaseClient | null = null;

/**
 * Get the Supabase client instance (server-side)
 */
export function getSupabaseClient(): SupabaseClient | null {
  const url = process.env.SUPABASE_URL || process.env.NEXT_PUBLIC_SUPABASE_URL;
  const key =
    process.env.SUPABASE_SERVICE_ROLE_KEY ||
    process.env.SUPABASE_ANON_KEY ||
    process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;

  if (!url || !key) {
    return null;
  }

  if (!cachedClient) {
    cachedClient = createClient(url, key, {
      auth: {
        persistSession: false,
        autoRefreshToken: false,
      },
    });
  }

  return cachedClient;
}
